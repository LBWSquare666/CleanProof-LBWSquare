"""Robot I/O interface: skill code depends only on this layer; the three backends (mujoco / ursim / ur3e) each implement it.

Method semantics follow ur_rtde (RTDEControlInterface / RTDEReceiveInterface), so the real-robot backend can forward directly.
Control clock: wait_tick() advances one control cycle in simulation, and on the real robot sleeps to the next tick by absolute deadline
(convention from our earlier UR3e work: if more than one tick behind, reset instead of catching up).
"""

from __future__ import annotations

from typing import Optional, Protocol, Sequence, runtime_checkable

import numpy as np

ROBOT_MODE_RUNNING = 7
SAFETY_MODE_NORMAL = 1
SAFETY_MODE_PROTECTIVE_STOP = 3
SAFETY_MODE_ROBOT_EMERGENCY_STOP = 6   # UR safety mode number: robot emergency stop (the console E-STOP sets this state in simulation)


@runtime_checkable
class RobotIO(Protocol):
    control_dt: float
    backend_name: str

    # Clock
    def now(self) -> float: ...
    def wait_tick(self) -> None: ...

    # Read-only state (base frame)
    def get_q(self) -> np.ndarray: ...
    def get_tcp_pose(self) -> np.ndarray: ...
    def get_tcp_speed(self) -> np.ndarray: ...
    def get_tcp_force(self) -> np.ndarray: ...
    def get_robot_mode(self) -> int: ...
    def get_safety_mode(self) -> int: ...
    def get_speed_fraction(self) -> float: ...
    def get_tcp_offset(self) -> np.ndarray: ...
    def get_payload(self) -> float: ...

    # Motion (single writer: the skill server)
    def speed_l(self, twist: Sequence[float], acceleration: float, time: float) -> bool: ...
    def speed_stop(self, deceleration: float = 0.5) -> None: ...
    def move_l(self, pose: Sequence[float], speed: float, acceleration: float) -> bool: ...
    def move_j(self, q: Sequence[float], speed: float, acceleration: float) -> bool: ...
    def get_ik(self, pose: Sequence[float], q_near: Sequence[float]) -> Optional[np.ndarray]: ...
    def stop_script(self) -> None: ...
    def close(self) -> None: ...
